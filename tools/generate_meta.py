"""Generate development-only Define hints from the owning runtime catalogs."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
NAME = re.compile(r'[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*\Z')
TYPE = re.compile(r'[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*(?:\[\])?'
                  r'(?:\s*&\s*[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*(?:\[\])?)*\Z')


def package_types(root=ROOT):
    """Keep package names and module types tied to explicit production declarations."""
    packages = {}
    for owner in ('lib', 'player', 'define'):
        path = root / owner / 'package_catalog.lua'
        content = path.read_text(encoding='utf-8')
        declarations = re.findall(r"(?:exports\.)?export\('([^']+)', require '([^']+)'\)", content)
        declarations += [(name, name) for name in re.findall(r"(?:exports\.)?export\('([^']+)', M\)", content)]
        for name, source in declarations:
            if name in packages:
                raise ValueError(f'{path}: duplicate package {name}')
            module_type = f'elxosc.mod.{source}'
            relative = source.replace('.', '/')
            candidates = [root / f'{relative}.lua', root / relative / 'init.lua',
                          root / 'lib' / f'{relative}.lua', root / 'lib' / relative / 'init.lua']
            module_path = next((candidate for candidate in candidates if candidate.is_file()), None)
            if module_path is None:
                raise ValueError(f'{path}: missing source {source}')
            module_content = module_path.read_text(encoding='utf-8')
            namespace = re.search(r'^---@namespace\s+(\S+)', module_content, re.M)
            source_declarations = re.findall(r'^---@(?:class|alias)\s+([^\s:<]+)', module_content, re.M)
            declared_types = {f'{namespace.group(1)}.{name}' if namespace else name
                              for name in source_declarations}
            if module_type not in declared_types:
                raise ValueError(f'{module_path}: missing module type {module_type}')
            packages[name] = module_type
    packages['player'] = 'elxosc.host.PlayerPackage'
    packages['mp'] = 'elxosc.host.MpPackage'
    return packages


def merge_declarations(packages, paths):
    merged = dict(packages)
    for path in paths:
        value = json.loads(Path(path).read_text(encoding='utf-8'))
        if not isinstance(value, dict) or set(value) != {'packages'} or not isinstance(value['packages'], list):
            raise ValueError(f'{path}: expected {{"packages": [{{"name": ..., "type": ...}}]}}')
        for index, declaration in enumerate(value['packages'], 1):
            label = f'{path}: packages[{index}]'
            if not isinstance(declaration, dict) or set(declaration) != {'name', 'type'}:
                raise ValueError(f'{label}: expected name and type')
            name, type_name = declaration['name'], declaration['type']
            if not isinstance(name, str) or not NAME.fullmatch(name) or name.endswith('.lua'):
                raise ValueError(f'{label}: invalid package name {name!r}')
            if not isinstance(type_name, str) or not TYPE.fullmatch(type_name):
                raise ValueError(f'{label}: type must be a named type or an intersection of named/array types')
            type_name = ' & '.join(part.strip() for part in type_name.split('&'))
            if name in merged and merged[name] != type_name:
                raise ValueError(f'{label}: package {name!r} conflicts: {merged[name]} versus {type_name}')
            merged[name] = type_name
    return merged


def render(packages, root=ROOT):
    lines = [
        '---@meta no-require',
        '-- Generated by tools/generate_meta.py; editor support only, never require this file.',
        '',
        '---@namespace elxosc',
        '---@using elxosc',
        '',
        '---@class meta.Packages',
    ]
    lines += [f"---@field ['{name}'] {type_name}" for name, type_name in packages.items()]
    lines += [
        '',
        '--- Returns a scoped shallow package without adding fields to the payload environment.',
        '--- Nonliteral/dynamic names have only a table fallback; declare their type for field hints.',
        '---@param name string',
        '---@return table',
    ]
    lines += [f"---@overload fun(name: '{name}'): {type_name}" for name, type_name in packages.items()]
    lines += [
        'function import_as(name) end',
        '',
        '--- Injects members into this scope; it returns no package. Prefer import_as for local hints.',
        '---@param name string',
        'function import(name) end',
        '',
        '--- Define require is the scope import alias, not the framework source loader.',
        '---@param name string',
        'function require(name) end',
        '',
        '--- Publishes data within the active Define payload transaction.',
        '---@param name string',
        '---@param data table?',
        'function mod(name, data) end',
        '',
        '---@param id string',
        '---@param widget elxosc.Widget|elxosc.Widget[]|nil',
        '---@param opts table<string, any>?',
        'function bind(id, widget, opts) end',
        '',
        '---@param ... any',
        'function print(...) end',
        '',
    ]
    content = (root / 'host/builtins.lua').read_text(encoding='utf-8')
    entries = re.findall(r'^        ([A-Za-z_][A-Za-z0-9_]*) = ', content, re.M)
    if len(entries) != len(set(entries)):
        raise ValueError('host/builtins.lua: duplicate default name')
    # Indexed access reuses the actual callable class and exact selected export type.
    dsl = (root / 'define/src/dsl.lua').read_text(encoding='utf-8')
    for name in entries:
        if name in ('new_widget', 'new_state'):
            # Indexed function aliases lose name-template constraints in the analyzer.
            # Reuse the source factory annotations verbatim for its global counterpart.
            doc = re.search(r'(---@generic[^\n]*\n(?:---@[^\n]*\n)+)function M\.' + name + r'\(', dsl)
            if doc is None:
                raise ValueError(f'define/src/dsl.lua: missing factory signature for {name}')
            lines += [doc.group(1).rstrip(), f'function {name}(name, parent) end']
        else:
            lines += [f"---@type elxosc.mod.host.builtins['{name}']\n{name} = nil"]
    return '\n'.join(line.replace('elxosc.', '') if line.startswith('---@')
                     and not line.startswith(('---@namespace ', '---@using '))
                     else line for line in lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--declarations', type=Path, action='append', default=[],
                        help='extension package/type JSON; repeat in composition order')
    parser.add_argument('--output', type=Path, default=ROOT / 'meta/elxosc.lua')
    parser.add_argument('--check', action='store_true', help='check an existing generated file without writing')
    args = parser.parse_args(argv)
    try:
        packages = merge_declarations(package_types(), args.declarations)
        output = render(packages)
        if args.check:
            if not args.output.is_file() or args.output.read_text(encoding='utf-8') != output:
                raise ValueError(f'{args.output}: generated metadata is out of date')
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(output, encoding='utf-8', newline='\n')
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    print(f'{len(packages)} package types; {args.output.name} {"checked" if args.check else "generated"}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
